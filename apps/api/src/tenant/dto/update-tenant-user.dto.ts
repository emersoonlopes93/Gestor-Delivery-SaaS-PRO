import { IsEmail, IsString, MinLength, IsOptional, IsBoolean, IsArray } from 'class-validator';

export class UpdateTenantUserDto {
  @IsEmail()
  @IsOptional()
  email?: string;

  @IsString()
  @IsOptional()
  name?: string;

  @IsString()
  @MinLength(6)
  @IsOptional()
  password?: string;

  @IsBoolean()
  @IsOptional()
  isActive?: boolean;

  @IsArray()
  @IsString({ each: true })
  @IsOptional()
  roles?: string[]; // Array of role slugs
}
